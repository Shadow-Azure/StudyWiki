#!/usr/bin/env node
// Tauri 命令目录生成器：扫描 src-tauri/src/lib.rs 的 #[tauri::command]（含 ///
// 文档注释与 generate_handler 注册表）及 `mod x;` 命令模块文件（注册项写成
// `x::cmd`），写入 docs/commands.md 与 docs/commands.en.md 两侧的生成区（区块
// 内容两侧逐字节一致）。`pnpm verify:commands` 即本脚本 --check：重新生成后
// 与磁盘逐行比对，源码改了没再生成即红。生成区外禁手改（见 docs/AGENTS.md）。

import { readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";

const ROOT = path.resolve("");
const SOURCE = "src-tauri/src/lib.rs";
const SRC_DIR = "src-tauri/src";
const SLUG = "commands-catalog";
const TARGETS = ["docs/commands.md", "docs/commands.en.md"];
const BEGIN = `<!-- BEGIN GENERATED ${SLUG} (scripts/gen-commands-catalog.mjs) — do not edit between markers -->`;
const END = `<!-- END GENERATED ${SLUG} -->`;

/** 单文件命令扫描：#[tauri::command] → {name, signature, docs}，按出现顺序。 */
function parseFileCommands(source, file) {
  const lines = source.split("\n");
  const commands = [];
  for (let i = 0; i < lines.length; i += 1) {
    if (!/^\s*#\[tauri::command\]/.test(lines[i])) continue;
    // 向上收集紧邻的 /// 文档注释
    const docs = [];
    for (let j = i - 1; j >= 0 && /^\s*\/\/\//.test(lines[j]); j -= 1) docs.unshift(lines[j].trim().replace(/^\/\/\/\s?/, ""));
    // 向下拼签名直到开括号；rustfmt 换行的参数表收敛成单行（"( " → "("、", )" → ")"）
    let signature = "";
    for (let j = i + 1; j < lines.length; j += 1) {
      signature += (signature ? " " : "") + lines[j].trim();
      if (lines[j].includes("{") || lines[j].includes(";")) {
        signature = signature
          .replace(/\{\s*$/, "")
          .replace(/;\s*$/, "")
          .replace(/\(\s+/g, "(")
          .replace(/,\s*\)/g, ")")
          .trim();
        break;
      }
    }
    const name = /(?:fn|async fn)\s+(\w+)/.exec(signature)?.[1];
    if (!name) throw new Error(`gen-commands-catalog: ${file} 第 ${i + 1} 行附近的命令解析不出函数名`);
    commands.push({ name, signature, docs });
  }
  return commands;
}

/** lib.rs 里的文件模块声明：`mod x;`（分号才是文件模块；`mod x {` 是内联模块，不算）。 */
export function fileModuleNames(source) {
  return [...source.matchAll(/^\s*(?:pub(?:\([^)]*\))?\s+)?mod\s+(\w+)\s*;/gm)].map((m) => m[1]);
}

/** 命令清单：lib.rs 裸名命令 + `mod x;` 模块文件命令（moduleSources：模块名 →
 *  源码；name 带 `x::` 前缀，与 generate_handler 注册项逐字一致），lib.rs 命令
 *  在前，模块命令按注册表首现顺序。不变量：每个命令都已注册，每个注册都有命令。 */
export function parseCommands(source, moduleSources = {}) {
  const libCommands = parseFileCommands(source, SOURCE);
  const modCommands = Object.entries(moduleSources).flatMap(([mod, src]) =>
    parseFileCommands(src, `${SRC_DIR}/${mod}.rs`).map((c) => ({ ...c, name: `${mod}::${c.name}` })),
  );

  // 注册表：generate_handler![...] 列出的名字（可跨行）。
  const registered = [];
  const handler = /tauri::generate_handler!\s*\[([^\]]*)\]/s.exec(source);
  if (handler)
    for (const item of handler[1].split(",")) {
      const name = item.trim();
      if (name) registered.push(name);
    }

  const declared = new Set([...libCommands, ...modCommands].map((c) => c.name));
  const registeredSet = new Set(registered);
  const unregistered = [...libCommands, ...modCommands]
    .filter((c) => !registeredSet.has(c.name))
    .map((c) => c.name);
  const undeclared = registered.filter((name) => !declared.has(name));
  if (unregistered.length || undeclared.length) {
    throw new Error(
      `gen-commands-catalog: 命令与 generate_handler 注册表不一致（未注册：${unregistered.join(", ") || "无"}；未声明：${undeclared.join(", ") || "无"}）`,
    );
  }

  const byName = new Map(modCommands.map((c) => [c.name, c]));
  return [...libCommands, ...registered.filter((name) => byName.has(name)).map((name) => byName.get(name))];
}

/** 渲染生成区全文（标记行含在内）。 */
export function renderRegion(commands) {
  const withModule = commands.some((c) => c.name.includes("::"));
  const body = [
    "```rust",
    `// Generated by scripts/gen-commands-catalog.mjs from ${SOURCE}${withModule ? " + command modules" : ""} — do not edit.`,
    `// Registered: ${commands.map((c) => c.name).join(", ")}`,
    "",
  ];
  for (const command of commands) {
    for (const doc of command.docs) body.push(`/// ${doc}`);
    body.push("#[tauri::command]");
    body.push(`${command.signature};`);
    body.push("");
  }
  body.push("```");
  return [BEGIN, ...body, END].join("\n");
}

/** 把生成区替换进文档（保留区块外人工内容），返回新全文。 */
export function spliceRegion(text, region) {
  const lines = text.split("\n");
  const begin = lines.findIndex((line) => line.trim() === BEGIN);
  const end = lines.findIndex((line) => line.trim() === END);
  if (begin === -1 || end === -1 || end < begin)
    throw new Error(`gen-commands-catalog: 文档缺 ${SLUG} 生成区标记对`);
  return [...lines.slice(0, begin), ...region.split("\n"), ...lines.slice(end + 1)].join("\n");
}

async function main() {
  const check = process.argv.includes("--check");
  const lib = await readFile(path.join(ROOT, SOURCE), "utf8");
  const moduleSources = {};
  for (const mod of fileModuleNames(lib)) {
    const file = path.join(ROOT, SRC_DIR, `${mod}.rs`);
    if (existsSync(file)) moduleSources[mod] = await readFile(file, "utf8");
  }
  const commands = parseCommands(lib, moduleSources);
  const region = renderRegion(commands);

  for (const target of TARGETS) {
    const file = path.join(ROOT, target);
    const current = await readFile(file, "utf8");
    const next = spliceRegion(current, region);
    if (next !== current) {
      if (check) {
        const currentLines = current.split("\n");
        const nextLines = next.split("\n");
        const diffAt = nextLines.findIndex((line, i) => line !== currentLines[i]) + 1;
        console.error(`gen-commands-catalog: ${target} 过期（第一处差异在第 ${diffAt} 行）；跑 pnpm run gen:commands`);
        process.exit(1);
      }
      await writeFile(file, next);
      console.log(`gen-commands-catalog: 写入 ${target}（${commands.length} 条命令）`);
    } else if (check) {
      console.log(`gen-commands-catalog: ${target} 新鲜`);
    }
  }
  if (!check) console.log(`gen-commands-catalog: done（${commands.length} 条命令）`);
}

if (import.meta.url === `file://${process.argv[1]}`) await main();
